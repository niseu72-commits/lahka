# Loop with Condition
# 0 is assigned to the variable x. The while loop will continue to execute as long as the condition x < 10 is true.
# Inside the loop, the current value of x is printed, and then x is incremented by 1. Once x reaches 10, the condition becomes false, and the loop ends.

x = 0
while x < 10:
    print(x)
    x += 1